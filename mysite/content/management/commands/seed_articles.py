class Command(BaseCommand):
    help = "افزودن مقاله‌های نمونه برنامه‌نویسی"

    def handle(self, *args, **options):
        created = 0
        for item in ARTICLES:
            _, is_new = Article.objects.get_or_create(
                title=item["title"],
                defaults={"summary": item["summary"], "body": item["body"]},
            )
            created += int(is_new)
        self.stdout.write(self.style.SUCCESS(f"{created} مقاله اضافه شد."))
